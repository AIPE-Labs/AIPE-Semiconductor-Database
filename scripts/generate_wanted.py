"""Write ``docs/wanted-measurements.md``: which measurements the database lacks most.

Built from the canonical corpus with the existing coverage rules
(``aipe_devices.services.coverage``) and the gap planner's protocol table. The coverage
rules test whether *any* evidence is present; they do not tell a manufacturer model from
a measurement, so the measured column is counted here from each record's origin.
``--check`` fails when the committed file is out of date.
"""

import argparse
from collections import Counter
from pathlib import Path

from aipe_devices.domain.device import CHARACTERISTICS
from aipe_devices.measurement.gap_planner import PROTOCOLS
from aipe_devices.repository.json_repository import JsonDeviceRepository
from aipe_devices.schema.enums import Availability, Origin
from aipe_devices.services.coverage.gaps import coverage_gaps

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "docs/wanted-measurements.md"
LABEL = {
    "conduction": "Static conduction (on-state voltage drop or RDS(on) against current and temperature)",
    "switching": "Double-pulse switching energies (Eon, Eoff against current, voltage, temperature, gate resistance)",
    "capacitance": "Capacitances and output-capacitance energy (Ciss, Coss, Crss, Eoss against voltage)",
    "reverse_conduction": "Reverse (third-quadrant) conduction and reverse recovery",
    "thermal": "Thermal impedance junction to case",
    "gate_charge": "Gate charge",
}


def render() -> str:
    repository = JsonDeviceRepository(ROOT / "data/canonical")
    devices = [repository.get(key) for key in repository.list()]
    no_data, no_measurement = Counter(), Counter()
    for device in devices:
        missing = {
            gap.rule.group
            for gap in coverage_gaps(device).entries
            if gap.status not in {Availability.AVAILABLE, Availability.NOT_APPLICABLE}
        }
        for group in PROTOCOLS:
            no_data[group] += group in missing
            if group in CHARACTERISTICS:
                data = getattr(device, group)
                records = (*data.scalars, *data.curves)
            else:
                records = device.thermal
            no_measurement[group] += not any(
                r.provenance.origin == Origin.MEASURED for r in records
            )
    total = len(devices)
    order = sorted(PROTOCOLS, key=lambda g: (-no_data[g], -no_measurement[g], g))
    lines = [
        "# Wanted measurements",
        "",
        "Generated by `python scripts/generate_wanted.py` from the canonical corpus; do not edit by hand.",
        "",
        f"The database holds {total} devices, all from manufacturer simulation models. "
        "It holds no laboratory measurement. Any measurement of any listed device is "
        "therefore new information; the table shows where even a model value is absent.",
        "",
        "| Measurement | Protocol category | Devices with no data at all | Devices with no measurement |",
        "| --- | --- | ---: | ---: |",
    ]
    for group in order:
        lines.append(
            f"| {LABEL[group]} | `{PROTOCOLS[group][1]}` | {no_data[group]} of {total} | "
            f"{no_measurement[group]} of {total} |"
        )
    lines += [
        "",
        "How to read it:",
        "",
        "- **No data at all**: not even the manufacturer model gives this quantity. "
        "A measurement, or a manufacturer's own data under an open licence, fills a hole.",
        "- **No measurement**: a model value exists, but nothing measured confirms it. "
        "Measurements at the model's own grid points make the two directly comparable.",
        "- Data for devices that are not in the database yet are welcome too.",
        "",
        "Limits of this list: it counts presence, not quality, and it does not rank "
        "devices against each other. For a specific converter design, "
        "`aipe-devices measurement-requests` produces a prioritised request "
        "([docs/dab-loss-screening.md](dab-loss-screening.md)).",
        "",
        "To contribute, see [CONTRIBUTING.md](../CONTRIBUTING.md).",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = render()
    if args.check:
        return int(not TARGET.is_file() or TARGET.read_text(encoding="utf-8") != text)
    TARGET.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
